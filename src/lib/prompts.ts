/** 2文推薦の入力 (確認できた情報だけを渡す。未確認の項目は省略し、推測で補わない) */
export interface TwoSentenceInput {
  /** ユーザーの悩み・関心・選書条件 (grill-me会話由来のまとめ) */
  userContext: string;
  title: string;
  author: string;
  /** 書籍の概要・内容情報 (書誌APIで確認できた場合のみ) */
  description: string | null;
  /** 選書理由として利用可能な事実情報 (選書時の理由) */
  selectionReason: string;
}

/** 2文推薦1冊分の入力欄(単冊版・バッチ版で共用)。
    未確認の概要は渡さない(推測・補完の禁止)。渡された情報だけが事実 */
function twoSentenceFields(input: TwoSentenceInput): string {
  return [
    `- ユーザーの悩み・関心・選書条件: ${input.userContext}`,
    `- 選定された書籍のタイトル: ${input.title}`,
    `- 著者名: ${input.author}`,
    ...(input.description !== null ? [`- 書籍の概要・内容情報: ${input.description}`] : []),
    `- 選書理由として利用可能な事実情報: ${input.selectionReason}`,
  ].join("\n");
}

