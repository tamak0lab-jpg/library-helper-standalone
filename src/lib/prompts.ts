/** 熱血プレゼンの入力 (確認できた情報だけを渡す。未確認の項目は省略し、推測で補わない) */
export interface PitchInput {
  /** 悩み・課題のまとめ (選書時のneeds。空ならgrill会話のユーザー発言連結) */
  needs: string;
  /** 候補の3冊 (原文プレースホルダーへ差し込む)。summary/reasonは選書API自身の説明で、
      grill経路のみ渡せる。著者探訪は確認済み書誌(confirmed)を送るため省略する */
  books: { title: string; author: string; summary?: string; reason?: string }[];
  /** プレゼン対象の位置 (0〜2 = 「⚪︎番目の本」) */
  index: number;
  /** 書誌APIで確認できた事実のみ (未照合はnull。未確認項目は含めない) */
  confirmed: {
    title?: string;
    author?: string;
    publisher?: string;
    publishedDate?: string;
    description?: string;
  } | null;
  /** その本に表示済みの2文推薦 (生成できていた場合のみ参考として渡す) */
  twoSentence: string | null;
}

/** 熱血プレゼン用プロンプトを組み立てる。
    [原文(プレースホルダーに選書出力を差し込み)] + [表現品質ルール(共通+固有)] +
    [統合層の出力形式] + [対象指定と確認済み情報] */
export function buildPitchPrompt(input: PitchInput): string {
  const selection = [
    `悩み・課題: ${input.needs}`,
    // 概要・おすすめ理由は渡された場合のみ記載する(未確認項目・undefinedを書かない)
    ...input.books.map((b, i) => {
      const details = [
        ...(b.summary !== undefined ? [`概要: ${b.summary}`] : []),
        ...(b.reason !== undefined ? [`おすすめ理由: ${b.reason}`] : []),
      ];
      return `${i + 1}. 『${b.title}』${b.author}${details.length > 0 ? ` — ${details.join(" / ")}` : ""}`;
    }),
  ].join("\n");
  const target = input.books[input.index];
  // 未確認の書誌は渡さない(推測・補完の禁止)。渡された情報だけが事実
  const confirmedLines =
    input.confirmed === null
      ? []
      : Object.entries({
          正式書名: input.confirmed.title,
          著者: input.confirmed.author,
          出版社: input.confirmed.publisher,
          刊行日: input.confirmed.publishedDate,
          概要: input.confirmed.description,
        })
          .filter(([, v]) => v !== undefined)
          .map(([k, v]) => `- ${k}: ${v}`);
  const context = [
    "# 対象の指定(システム連携用)",
    `今回の「⚪︎番目の本」は、${input.index + 1}番目の本『${target.title}』(${target.author})です。この1冊についてプレゼンを作成してください。`,
    ...(confirmedLines.length > 0
      ? ["", "# この本について確認済みの書誌情報(確認できている事実はこれだけ)", ...confirmedLines]
      : []),
    ...(input.twoSentence !== null
      ? ["", "# この本に表示済みの2文推薦(参考)", input.twoSentence]
      : []),
  ].join("\n");
  return [
    HOT_PITCH_PROMPT.replace(PITCH_PLACEHOLDER, selection),
    expressionRulesFor("pitch"),
    PITCH_OUTPUT_FORMAT,
    context,
  ].join("\n\n---\n\n");
}

